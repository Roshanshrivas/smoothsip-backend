// Category name mapping
const categoryMap = {
  1: 'Insulated Tumblers',
  2: 'Travel Tumblers',
  3: 'Sports Tumblers',
  4: 'Coffee Tumblers',
  5: 'Limited Edition',
};

// ---------- Helper to generate slug ----------
const generateSlug = (text) =>
  text.toLowerCase().replace(/[^a-z0-9]/g, '-').replace(/-+/g, '-');

// ---------- SEED FUNCTION ----------
const seedDatabase = async () => {
  try {
    await mongoose.connect(process.env.MONGO_URI);

    // Clear existing products (optional)
    await Product.deleteMany({});

    // 3. Create categories with explicit slug
    const categoryIds = {};
    for (const [id, name] of Object.entries(categoryMap)) {
      const slug = generateSlug(name);
      let category = await Category.findOne({ name });
      if (!category) {
        // Create with both name and slug
        category = await Category.create({
          name,
          slug,
          status: 'Active',        // <-- use the correct schema field
          description: `All ${name} products`,
        });
      } else {
        // If category exists but slug is missing, update it (optional)
        if (!category.slug) {
          category.slug = slug;
          await category.save();
        }
      }
      categoryIds[id] = category._id;
    }

    // 4. Transform products (unchanged)
    const productsToInsert = allProducts.map((p) => ({
      name: p.title,
      slug: generateSlug(p.title),
      description: `Premium ${p.material} tumbler with ${p.size} capacity. Keeps drinks hot or cold for hours.`,
      price: p.price,
      comparePrice: p.oldPrice || p.price * 1.2,
      costPrice: Math.round(p.price * 0.6),
      sku: `SKU-${p.id}-${p.color.replace(/\s/g, '')}-${p.size}`,
      barcode: `BAR${String(p.id).padStart(6, '0')}`,
      images: [p.image],
      mainImage: p.image,
      category: categoryIds[p.categoryId] || null,
      tags: [p.tag, p.color, p.size, p.material].filter(Boolean),
      stock: p.inStock ? 100 : 0,
      weight: 0.5,
      dimensions: { length: 8, width: 8, height: 20 },
      isCustomizable: false,
      customizationOptions: {
        text: { enabled: false, maxLength: 20, defaultText: '' },
        logo: { enabled: false, maxFileSize: 2, allowedFormats: ['png', 'svg'] },
        font: { enabled: false, options: [] },
        color: { enabled: false, options: [] }
      },
      status: 'Active',
      ratingsAverage: p.rating || 0,
      ratingsCount: p.reviews || 0,
      salesCount: 0,
      totalRevenue: 0,
    }));

    // 5. Insert products
    const result = await Product.insertMany(productsToInsert);

    await mongoose.disconnect();
    process.exit(0);
  } catch (error) {
    console.error('❌ Seeding failed:', error);
    await mongoose.disconnect();
    process.exit(1);
  }
};

seedDatabase();